import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

export const outputFileNames = [
  'resolved-contract.json',
  'diagnostics.json',
  'contract-index.json',
  'contract.refs.ts',
  'build-manifest.json',
] as const;

export type OutputFileName = (typeof outputFileNames)[number];
export type CompilationFiles = Readonly<Partial<Record<OutputFileName, string>>>;

export interface GeneratedRefInventory {
  readonly entities: readonly string[];
  readonly prototypes: readonly string[];
  readonly relationships: readonly string[];
  readonly systems: readonly string[];
}

function renderRefMap(ids: readonly string[], kind: string, indentation: string): string[] {
  if (ids.length === 0) {
    return [`${indentation}{}`];
  }

  const lines = [`${indentation}{`];
  for (const id of [...ids].sort()) {
    const quotedId = JSON.stringify(id);
    lines.push(`${indentation}  ${quotedId}: contractRef<${JSON.stringify(kind)}>(${quotedId}),`);
  }
  lines.push(`${indentation}}`);
  return lines;
}

export function renderGeneratedRefs(inventory: GeneratedRefInventory): string {
  const lines = [
    '// Generated by @antiky/contracts. Do not edit; regenerate with antiky-contract compile.',
    "import { contractRef } from '@antiky/contracts/ir';",
    '',
    'export const refs = {',
  ];

  for (const [name, kind, ids] of [
    ['entities', 'entity', inventory.entities],
    ['prototypes', 'prototype', inventory.prototypes],
    ['relationships', 'relationship', inventory.relationships],
    ['systems', 'system', inventory.systems],
  ] as const) {
    const renderedMap = renderRefMap(ids, kind, '  ');
    lines.push(`  ${name}: ${renderedMap[0]?.trimStart() ?? '{}'}`);
    lines.push(...renderedMap.slice(1));
    lines[lines.length - 1] = `${lines.at(-1)},`;
  }

  lines.push('} as const;', '');
  return lines.join('\n');
}

async function writeAtomically(path: string, contents: string): Promise<void> {
  const temporaryPath = `${path}.${process.pid}.tmp`;
  try {
    await writeFile(temporaryPath, contents, 'utf8');
    await rename(temporaryPath, path);
  } finally {
    await rm(temporaryPath, { force: true });
  }
}

/** Emit only known compiler outputs and remove stale generated outputs absent from this result. */
export async function emitCompilationFiles(outputDirectory: string, files: CompilationFiles): Promise<void> {
  await mkdir(outputDirectory, { recursive: true });

  for (const fileName of outputFileNames) {
    const contents = files[fileName];
    const outputPath = join(outputDirectory, fileName);
    if (contents === undefined) {
      await rm(outputPath, { force: true });
      continue;
    }
    await writeAtomically(outputPath, contents);
  }
}
