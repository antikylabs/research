import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const packageDirectory = fileURLToPath(new URL("..", import.meta.url));
const sourcePath = resolve(packageDirectory, "src/shaders/pipeline.shader.ts");
const generatedDirectory = resolve(packageDirectory, "src/generated");
const bundled = await build({
  entryPoints: [sourcePath],
  bundle: true,
  format: "esm",
  platform: "node",
  write: false,
});
const moduleSource = bundled.outputFiles[0].text;
const moduleUrl = `data:text/javascript;base64,${Buffer.from(moduleSource).toString("base64")}`;
const shaderModule = await import(moduleUrl);
const shaders = shaderModule.buildArtifacts();
const generatedModule = `// Generated by the BroMetal-style AOT compiler. Do not edit.\nexport const brometalShaders = ${JSON.stringify(shaders)};\n`;

await mkdir(generatedDirectory, { recursive: true });
await Promise.all([
  ...Object.entries(shaders).map(([name, wgsl]) =>
    writeFile(resolve(generatedDirectory, `${name}.wgsl`), wgsl),
  ),
  writeFile(
    resolve(generatedDirectory, "pipeline.generated.ts"),
    generatedModule,
  ),
]);
